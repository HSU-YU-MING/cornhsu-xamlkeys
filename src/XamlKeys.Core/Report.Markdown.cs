using System.Globalization;
using System.Text;

namespace XamlKeys.Core;

/// <summary>
/// Markdown 報告（<c>--md</c>）—— 給 PR 留言用。形狀照 XamlContrast 的 <c>Report.ToMarkdown</c>。
///
/// 為什麼行內註記不夠：<c>::error</c> 只標在出問題的那一行，PR 上沒有總覽 —— reviewer 看不到
/// 「有幾本字典沒讀到、有幾個查找是執行期組出來的」。而那正是「unused 可不可信」的前提
/// （憲法第二條：「工具沒看到」與「看到了沒問題」必須分得開），所以**看不到的東西放在最前面**，
/// 先於 finding 的表。
///
/// ⚠ 這份報告會貼成 PR 留言，而鍵名、檔案路徑、訊息（訊息裡帶著鍵名與路徑）、讀不到的字典來源、
///   XML 解析器的訊息、C# 的查找運算式都是**被掃的 repo 寫的**。它們一律走 <see cref="Code"/>：
///   GitHub 只有在 code span 裡不處理 <c>[文字](網址)</c>、圖片、<c>@帳號</c> 與 <c>www.</c> 的自動連結，
///   反斜線跳脫擋不住後兩個（Parity 2.3.1、XamlContrast 1.2.1 都因此出過安全修正）。
///   沒有「一般文字版」的跳脫函式 —— 有了就會有人拿它來放掃描來的字串。
///
/// 其他規矩：數字一律 InvariantCulture；全文 ASCII（emoji 用 GitHub 的 <c>:x:</c> 短碼，
/// 跟主控台、JSON 同一條 <c>All_console_and_report_text_is_ascii</c>）；沒有時間戳（同樣的輸入同樣的檔）。
/// </summary>
public static class ReportMarkdown
{
    /// <summary>每一級最多列幾筆。GitHub 留言上限約 65,536 字（Action 另外在 60,000 字截斷），
    /// 舊專案第一次跑可以有上千筆 —— 列不完的講清楚還有多少、完整的在哪裡。</summary>
    public const int MaxRowsPerSeverity = 50;

    /// <summary>「看不到的東西」逐項列出時，每一類最多列幾個（讀不到的字典、解析失敗的檔、動態查找、沒寫理由的 ignore）。</summary>
    public const int MaxDetailsPerKind = 10;

    /// <summary>一格最多幾個字。鍵名與訊息是被掃的 repo 寫的，一個十萬字的鍵名不該把整則留言吃掉。</summary>
    public const int MaxCellLength = 200;

    public static string ToMarkdown(AnalysisResult r, string toolVersion, int exitCode)
    {
        var inv = CultureInfo.InvariantCulture;
        var sb = new StringBuilder();
        var fail = r.CountSeverity(Severity.Fail);
        var warn = r.CountSeverity(Severity.Warn);
        var info = r.CountSeverity(Severity.Info);

        sb.Append("## XamlKeys - resource key audit\n\n");

        var verdict = exitCode switch
        {
            0 => ":white_check_mark: **PASS**",
            3 => ":warning: **NOT TRUSTWORTHY**",
            _ => ":x: **FAIL**",
        };
        sb.Append(string.Create(inv,
            $"{verdict} - **{fail} fail**, {warn} warn, {info} info - " +
            $"{r.XamlFiles} XAML file(s), {r.Dictionaries} dictionar(ies), {r.KeysDefined} key(s), {r.References} reference(s); " +
            $"merged dictionaries resolved {r.MergeEdgesResolved}/{r.MergeEdges} ({r.Coverage.ToString("F1", inv)}%)\n\n"));

        WriteBlindSpots(sb, r, inv);

        // ── finding，依等級分組 ───────────────────────────────────────────
        if (r.Findings.Count == 0)
            sb.Append("No findings.\n\n");

        foreach (var sev in (ReadOnlySpan<Severity>)[Severity.Fail, Severity.Warn, Severity.Info])
        {
            var group = r.Findings.Where(f => f.Severity == sev)
                                  .OrderBy(f => f.Location.File, StringComparer.Ordinal)
                                  .ThenBy(f => f.Location.Line)
                                  .ToList();
            if (group.Count == 0) continue;

            var slug = Finding.SeveritySlug(sev);
            // info（external、shadowed-identical）不擋 gate，收在 <details> 裡：留言打開先看到的是要處理的
            if (sev == Severity.Info)
                sb.Append(string.Create(inv, $"<details><summary>info ({group.Count}) - not gated</summary>\n\n"));
            else
                sb.Append(string.Create(inv, $"### {slug} ({group.Count})\n\n"));

            sb.Append("| Location | Kind | Key | Message |\n");
            sb.Append("|---|---|---|---|\n");
            foreach (var f in group.Take(MaxRowsPerSeverity))
            {
                var kind = Finding.KindSlug(f.Kind);
                if (f.Side != ThemeSide.Neutral) kind += $" [{Finding.SideSlug(f.Side)}]";
                sb.Append(string.Create(inv,
                    $"| {Code($"{f.Location.File}:{f.Location.Line}")} | {kind} | {Code(f.Key)} | {Code(f.Message)} |\n"));
            }
            sb.Append('\n');

            if (group.Count > MaxRowsPerSeverity)
                sb.Append(string.Create(inv,
                    $"_... and {group.Count - MaxRowsPerSeverity} more {slug} finding(s), not listed here. " +
                    $"The full list is in the JSON report (`--json`; the GitHub Action uploads it as a workflow artifact)._\n\n"));

            if (sev == Severity.Info) sb.Append("</details>\n\n");
        }

        sb.Append(string.Create(inv,
            $"<sub>Generated by XamlKeys {Code(toolVersion, table: false)} - static scope audit for XAML resource keys</sub>\n"));
        return sb.ToString();
    }

    /// <summary>
    /// 工具沒看到的東西。順序：先是「結果不可信」與會讓 unused 不完整的那幾類（逐項列出），
    /// 再是「被算成有人用／不報」的計數。跟主控台的 note、HTML 的 "What this run could not see" 是同一組。
    /// </summary>
    private static void WriteBlindSpots(StringBuilder sb, AnalysisResult r, CultureInfo inv)
    {
        var any = false;
        void Head()
        {
            if (any) return;
            sb.Append("### What this run could not see\n\n");
            any = true;
        }

        if (r.Untrustworthy(out var reason))
        {
            Head();
            // reason 是工具自己寫的句子（數字與門檻），不含掃描來的字串
            sb.Append($"> :warning: **Result is not trustworthy** - {reason}\n\n");
        }

        if (r.ExternalSources.Count > 0)
        {
            Head();
            sb.Append(string.Create(inv,
                $"> :warning: **{r.ExternalSources.Count} merged dictionar(ies) could not be read** - " +
                $"'unused' is incomplete for keys they may define:\n"));
            foreach (var s in r.ExternalSources.Take(MaxDetailsPerKind))
                sb.Append($"> - {Code(s, table: false)}\n");
            More(sb, r.ExternalSources.Count, inv, "> ");
            sb.Append('\n');
        }

        if (r.ParseErrors.Count > 0)
        {
            Head();
            sb.Append(string.Create(inv,
                $"> :warning: **{r.ParseErrors.Count} file(s) failed to parse** - references inside them were not seen:\n"));
            foreach (var e in r.ParseErrors.Take(MaxDetailsPerKind))
                sb.Append($"> - {Code(e.File, table: false)}: {Code(e.Message, table: false)}\n");
            More(sb, r.ParseErrors.Count, inv, "> ");
            sb.Append('\n');
        }

        if (r.DynamicKeySites.Count > 0)
        {
            Head();
            sb.Append(string.Create(inv,
                $"**{r.DynamicKeySites.Count} runtime-composed resource lookup(s) in C#** - " +
                $"the keys they reach cannot be seen statically (see `usedAtRuntime` in the config):\n"));
            foreach (var d in r.DynamicKeySites.Take(MaxDetailsPerKind))
                sb.Append(string.Create(inv,
                    $"- {Code($"{d.Location.File}:{d.Location.Line}", table: false)} {Code(d.Expression, table: false)}\n"));
            More(sb, r.DynamicKeySites.Count, inv, "");
            sb.Append('\n');
        }

        if (r.InvalidIgnores.Count > 0)
        {
            Head();
            sb.Append(string.Create(inv,
                $"**{r.InvalidIgnores.Count} ignore comment(s) have no reason, or a commented-out element or text after them,** " +
                $"and were ignored themselves (write `<!-- xamlkeys-ignore: why -->` right before the element):\n"));
            foreach (var l in r.InvalidIgnores.Take(MaxDetailsPerKind))
                sb.Append($"- {Code(l.ToString(), table: false)}\n");
            More(sb, r.InvalidIgnores.Count, inv, "");
            sb.Append('\n');
        }

        // 計數類：都是工具自己的句子，沒有掃描來的字串
        var notes = new List<string>();
        void Note(int n, string text)
        {
            if (n > 0) notes.Add(string.Create(inv, $"{n} {text}"));
        }
        Note(r.LibraryKeysNotChecked, "key(s) in library projects were not checked for usage (a library's keys are its public API)");
        Note(r.LibraryUnresolvedReferences, "reference(s) in library projects resolve to nothing in their own project and are not gated");
        Note(r.CrossProjectReferences, "reference(s) point at keys defined in another project in this tree; their scope was not checked");
        Note(r.KeysMatchingComposedLookups, "key(s) counted as used because they match a key C# composes at runtime");
        Note(r.KeysNamedNearDynamicLookups, "key(s) counted as used because their name appears as a string in a C# file that looks resources up by variable");
        Note(r.KeysNamedInCode, "more key(s) counted as used because their name appears as a string in the same project's C#");
        Note(r.DynamicKeysNamedInCode, "DynamicResource reference(s) not reported as dangling because C# names the key (added at runtime)");
        Note(r.KeysAddedInCode, "reference(s) name a key that C# adds to resources; not reported as dangling");
        Note(r.KeysMatchingComposedWrites, "reference(s) match a prefix C# composes keys from when it writes resources; not reported as dangling");
        Note(r.KeyedDictionaries, "keyed dictionar(ies) treated as runtime-selected alternatives");
        Note(r.RuntimeSelectedFamilyFiles, "unmerged dictionar(ies) look like a runtime-selected family and were not reported as orphans");
        Note(r.VariantDictionaryGroups, "dictionary pair(s) look like locale/theme variants and were not reported as shadowing");
        Note(r.FrameworkProvided, "reference(s) resolve to keys the UI framework or a bundled theme list provides");
        Note(r.FrameworkKeyOverrides, "key(s) redefine a key the framework itself reads; not reported as unused");
        Note(r.TestFilesExcluded, "XAML file(s) under test paths were skipped (set includeTests in the config to scan them)");
        Note(r.Suppressed - r.BaselineSuppressed, "finding(s) suppressed by ignore comments or config");
        Note(r.BaselineSuppressed, "known finding(s) hidden by the baseline");

        if (notes.Count > 0)
        {
            Head();
            sb.Append("<details><summary>Counted as used, not gated or suppressed</summary>\n\n");
            foreach (var n in notes) sb.Append($"- {n}\n");
            sb.Append("\n</details>\n\n");
        }
    }

    private static void More(StringBuilder sb, int total, CultureInfo inv, string prefix)
    {
        if (total > MaxDetailsPerKind)
            sb.Append(string.Create(inv, $"{prefix}- ... and {total - MaxDetailsPerKind} more (see the JSON report)\n"));
    }

    /// <summary>
    /// Markdown 的 code span：圍欄用比內容裡最長的反引號串多一個的反引號（CommonMark），內容裡有反引號時
    /// 兩邊各墊一個空白。換行收成空白。表格裡的 <c>|</c> 照樣要跳脫（GFM 先切欄再解析行內）；
    /// 表格外的 code span 不處理反斜線，跳脫了會印出來，所以 <c>table: false</c> 不跳脫。
    /// 照 XamlContrast 的 <c>Report.Code</c>，多一道長度上限（<see cref="MaxCellLength"/>）。
    /// ⚠ 只用一個反引號包的話，鍵名裡一個反引號就提早結束 code span，後面的 <c>[x](http://…)</c> 就變成連結。
    /// </summary>
    internal static string Code(string s, bool table = true)
    {
        if (s.Length > MaxCellLength)
        {
            var cut = MaxCellLength;
            if (char.IsHighSurrogate(s[cut - 1])) cut--;   // 不把一個字切成兩半
            s = s[..cut] + "...";
        }

        var body = (table ? s.Replace("|", "\\|") : s)
            .Replace("\r\n", " ").Replace('\r', ' ').Replace('\n', ' ')
            .Replace((char)0x2028, ' ').Replace((char)0x2029, ' ');   // Unicode line / paragraph separators
        var longest = 0;
        for (int i = 0, run = 0; i < body.Length; i++)
        {
            run = body[i] == '`' ? run + 1 : 0;
            longest = Math.Max(longest, run);
        }
        var fence = new string('`', longest + 1);
        var pad = longest > 0 || body.StartsWith(' ') || body.EndsWith(' ') ? " " : "";
        // 全是空白的內容 CommonMark 不剝掉兩邊的空白 —— 照樣包起來就好；空字串給一個看得見的記號
        if (body.Length == 0) return "`(empty)`";
        return fence + pad + body + pad + fence;
    }
}
