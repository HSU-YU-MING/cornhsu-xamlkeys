using System.Diagnostics;
using System.Text;
using XamlKeys.Core;

namespace XamlKeys.Tests;

/// <summary>
/// Markdown 報告（<c>--md</c>，給 PR 留言用；Action 的 <c>comment</c> 預設打開）。
///
/// 兩件事要守：
///   1. **看不到的東西放在最前面**：讀不到的字典、解析失敗的檔、執行期組出來的查找。
///      只列 finding 的話，reviewer 會以為表上那幾筆就是全部 —— 那就是謊報健康。
///   2. **掃描來的字串不能在留言裡變成連結、圖片或 @ 提及**。鍵名、檔名、訊息都是被掃的 repo 寫的，
///      GitHub 只在 code span 裡不處理它們（反斜線擋不住提及，也擋不住 www. 的自動連結）。
///      照 XamlContrast 的 MarkdownInjectionTests：照 CommonMark 把 code span 拿掉，看剩下的文字，不必連網。
/// </summary>
public class MarkdownReportTests : IDisposable
{
    private readonly DirectoryInfo _dir = Directory.CreateTempSubdirectory("xamlkeys-md");
    public void Dispose() => _dir.Delete(true);

    private const string Ns = "xmlns=\"http://schemas.microsoft.com/winfx/2006/xaml/presentation\" " +
                              "xmlns:x=\"http://schemas.microsoft.com/winfx/2006/xaml\"";

    private void Put(string rel, string content)
    {
        var path = Path.Combine(_dir.FullName, rel);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
    }

    private AnalysisResult Analyze()
    {
        Put("App.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\"><PropertyGroup><OutputType>WinExe</OutputType></PropertyGroup></Project>");
        return Analyzer.Run(_dir.FullName, new Config());
    }

    private static AnalysisResult Demo() => Analyzer.Run(TestPaths.Demo, new Config { MinCoverage = 0 });

    // ── 結論與內容 ─────────────────────────────────────────────────────────

    [Fact]
    public void The_verdict_follows_the_exit_code()
    {
        // 報告的結論必須跟退出碼一致，不能各說各話
        var r = Demo();
        Assert.Contains(":x: **FAIL**", ReportMarkdown.ToMarkdown(r, "t", 1));
        Assert.Contains(":white_check_mark: **PASS**", ReportMarkdown.ToMarkdown(r, "t", 0));
        Assert.Contains(":warning: **NOT TRUSTWORTHY**", ReportMarkdown.ToMarkdown(r, "t", 3));
        Assert.DoesNotContain(":x:", ReportMarkdown.ToMarkdown(r, "t", 0));
    }

    [Fact]
    public void The_header_carries_the_counts_and_the_scan_size()
    {
        var r = Demo();
        var md = ReportMarkdown.ToMarkdown(r, "0.0.0-test", 1);

        Assert.StartsWith("## XamlKeys - resource key audit", md);
        Assert.Contains($"**{r.CountSeverity(Severity.Fail)} fail**, {r.CountSeverity(Severity.Warn)} warn, {r.CountSeverity(Severity.Info)} info", md);
        Assert.Contains($"{r.XamlFiles} XAML file(s)", md);
        Assert.Contains($"merged dictionaries resolved {r.MergeEdgesResolved}/{r.MergeEdges}", md);
        Assert.Contains("| Location | Kind | Key | Message |", md);
        Assert.EndsWith("<sub>Generated by XamlKeys `0.0.0-test` - static scope audit for XAML resource keys</sub>\n", md);
    }

    [Fact]
    public void What_the_run_could_not_see_comes_before_the_findings()
    {
        // demo 有一本讀不到的外部字典與一個組出來的查找：都要在第一張表之前
        var r = Analyzer.Run(TestPaths.Demo, new Config());
        Assert.True(r.Untrustworthy(out _));
        var md = ReportMarkdown.ToMarkdown(r, "t", 3);

        var blind = md.IndexOf("### What this run could not see", StringComparison.Ordinal);
        var firstTable = md.IndexOf("| Location |", StringComparison.Ordinal);
        Assert.True(blind > 0 && blind < firstTable, "the blind spots must precede the findings");
        Assert.True(md.IndexOf("**Result is not trustworthy**", StringComparison.Ordinal) is var t && t > blind && t < firstTable);
        Assert.Contains("merged dictionar(ies) could not be read", md);
        Assert.Contains("`pack://application:,,,/ImaginaryLib;component/Themes/Generic.xaml`", md);
        Assert.Contains("runtime-composed resource lookup(s) in C#", md);
        Assert.Contains("`FindResource($\"Icon{name}\")`", md);
    }

    [Fact]
    public void Every_finding_becomes_one_row_grouped_by_severity()
    {
        var r = Demo();
        var md = ReportMarkdown.ToMarkdown(r, "t", 1);

        var rows = md.Split('\n').Count(l => l.StartsWith("| `", StringComparison.Ordinal));
        Assert.Equal(r.Findings.Count, rows);
        Assert.True(md.IndexOf("### fail (", StringComparison.Ordinal) < md.IndexOf("### warn (", StringComparison.Ordinal));
        // info 不擋 gate：收在 <details> 裡
        Assert.Contains($"<details><summary>info ({r.CountSeverity(Severity.Info)}) - not gated</summary>", md);
    }

    [Fact]
    public void The_same_input_produces_the_same_file()
    {
        Assert.Equal(ReportMarkdown.ToMarkdown(Demo(), "t", 1), ReportMarkdown.ToMarkdown(Demo(), "t", 1));
    }

    [Fact]
    public void Numbers_do_not_follow_the_current_culture()
    {
        // 德文的文化設定把 66.7 寫成 66,7：留言裡的數字要跟 JSON 一樣
        var before = System.Globalization.CultureInfo.CurrentCulture;
        try
        {
            System.Globalization.CultureInfo.CurrentCulture = System.Globalization.CultureInfo.InvariantCulture;
            var expected = ReportMarkdown.ToMarkdown(Demo(), "t", 1);
            try { System.Globalization.CultureInfo.CurrentCulture = new System.Globalization.CultureInfo("de-DE"); }
            catch (System.Globalization.CultureNotFoundException) { return; }   // globalization-invariant 模式
            Assert.Contains("(66.7%)", expected);
            Assert.Equal(expected, ReportMarkdown.ToMarkdown(Demo(), "t", 1));
        }
        finally { System.Globalization.CultureInfo.CurrentCulture = before; }
    }

    [Fact]
    public void A_long_list_is_cut_and_says_where_the_rest_is()
    {
        var keys = string.Concat(Enumerable.Range(0, ReportMarkdown.MaxRowsPerSeverity + 7)
            .Select(i => $"<SolidColorBrush x:Key=\"Unused{i:D3}\" Color=\"#111\" />"));
        Put("App.xaml", $"<Application {Ns}><Application.Resources><ResourceDictionary>{keys}</ResourceDictionary></Application.Resources></Application>");

        var r = Analyze();
        var md = ReportMarkdown.ToMarkdown(r, "t", 0);

        Assert.Equal(ReportMarkdown.MaxRowsPerSeverity + 7, r.Findings.Count(f => f.Kind == FindingKind.Unused));
        Assert.Equal(ReportMarkdown.MaxRowsPerSeverity, md.Split('\n').Count(l => l.StartsWith("| `App.xaml:", StringComparison.Ordinal)));
        Assert.Contains("... and 7 more warn finding(s)", md);
        Assert.Contains("JSON report", md);
    }

    [Fact]
    public void A_huge_key_is_clipped_inside_its_code_span()
    {
        var key = new string('K', 5000);
        Put("App.xaml", $"<Application {Ns}><Application.Resources><ResourceDictionary><SolidColorBrush x:Key=\"{key}\" Color=\"#111\" /></ResourceDictionary></Application.Resources></Application>");

        var md = ReportMarkdown.ToMarkdown(Analyze(), "t", 0);

        Assert.DoesNotContain(new string('K', ReportMarkdown.MaxCellLength + 1), md);
        Assert.Contains("`" + new string('K', ReportMarkdown.MaxCellLength) + "...`", md);
    }

    // ── 掃描來的字串留在 code span 裡 ──────────────────────────────────────

    /// <summary>鍵名：x:Key 可以是任何字串。換行用 &amp;#10; 寫（XML 解析後是真的換行）。</summary>
    public static TheoryData<string, string> HostileKeys => new()
    {
        { "[x](http://evil.example)", "[x](http://evil.example)" },
        { "![pixel](http://evil.example/p.png)", "![pixel](http://evil.example/p.png)" },
        { "@someone please", "@someone please" },
        { "www.evil.example now", "www.evil.example now" },
        { "a` [x](http://evil.example) `b", "a` [x](http://evil.example) `b" },          // 反引號：包一層就跳得出來
        { "a``` [x](http://evil.example) ```b", "a``` [x](http://evil.example) ```b" },
        { "p | [x](http://evil.example) | q", @"p \| [x](http://evil.example) \| q" },   // 表格的 |：沒跳脫就多切出欄
        { "n&#10;| [x](http://evil.example) |&#10;@someone", @"n \| [x](http://evil.example) \| @someone" }, // 換行：沒收掉就跳出表格
    };

    [Theory]
    [MemberData(nameof(HostileKeys))]
    public void A_key_cannot_write_markdown(string xmlKey, string shown)
    {
        Put("App.xaml", $"""
            <Application {Ns}>
              <Application.Resources><ResourceDictionary>
                <SolidColorBrush x:Key="{xmlKey}" Color="#111" />
              </ResourceDictionary></Application.Resources>
            </Application>
            """);

        var r = Analyze();
        Assert.Contains(r.Findings, f => f.Kind == FindingKind.Unused);   // 確認真的走到會帶鍵名的那條
        var md = ReportMarkdown.ToMarkdown(r, "t", 0);

        Assert.Contains(shown, md);   // 還是要點名是哪個鍵，只是不能變成語法
        AssertNothingEscaped(md);
        AssertTableRowsHaveFourCells(md);
    }

    /// <summary>檔名：在三個作業系統上都合法（Windows 不收 | 與 :）。</summary>
    public static TheoryData<string> HostileFileNames =>
    [
        "[click](evil.html).xaml",
        "![pixel](evil.png).xaml",
        "@someone x.xaml",
        "www.evil.example x.xaml",
        "a` [click](evil.html) `b.xaml",
    ];

    [Theory]
    [MemberData(nameof(HostileFileNames))]
    public void A_file_name_in_a_finding_cannot_write_markdown(string name)
    {
        // 沒人合併的字典：檔名進 Location 與 orphan-dictionary 的 Key
        Put("App.xaml", $"<Application {Ns}><Application.Resources><ResourceDictionary><SolidColorBrush x:Key=\"A\" Color=\"#1\" /></ResourceDictionary></Application.Resources></Application>");
        Put($"Themes/{name}", $"<ResourceDictionary {Ns}><SolidColorBrush x:Key=\"B\" Color=\"#2\" /></ResourceDictionary>");

        var r = Analyze();
        Assert.Contains(r.Findings, f => f.Kind == FindingKind.OrphanDictionary);
        var md = ReportMarkdown.ToMarkdown(r, "t", 0);

        Assert.Contains(name, md);
        AssertNothingEscaped(md);
        AssertTableRowsHaveFourCells(md);
    }

    [Theory]
    [MemberData(nameof(HostileFileNames))]
    public void A_file_name_in_a_parse_failure_cannot_write_markdown(string name)
    {
        Put("App.xaml", $"<Application {Ns}><Application.Resources><ResourceDictionary><SolidColorBrush x:Key=\"A\" Color=\"#1\" /></ResourceDictionary></Application.Resources></Application>");
