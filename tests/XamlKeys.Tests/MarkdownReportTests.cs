    [Fact]
    public void The_check_itself_sees_what_escaped_a_code_span()
    {
        // 這條檢查失效的話，上面全部都會靜靜地綠
        Assert.Contains("evil", OutsideCodeSpans("[x](evil.html)"));
        Assert.Contains("evil", OutsideCodeSpans("`a` [x](evil.html) `b`"));   // 單反引號包住帶反引號的名字
        Assert.DoesNotContain("evil", OutsideCodeSpans("`` a` [x](evil.html) `b ``"));
        Assert.Contains("evil", OutsideCodeSpans("` [x](evil.html)"));         // 沒有配對的反引號不算 code span
        Assert.Throws<Xunit.Sdk.TrueException>(() => AssertTableRowsHaveFourCells("| `a` | b | `c|d` | e |\n"));
    }

    // ── 輔助 ───────────────────────────────────────────────────────────────

    private static void AssertNothingEscaped(string markdown)
    {
        var outside = OutsideCodeSpans(markdown);
        Assert.DoesNotContain("evil", outside);
        Assert.DoesNotContain("@someone", outside);
        Assert.DoesNotContain("![", outside);
        Assert.DoesNotContain("www.", outside);
    }

    /// <summary>GFM 先以沒跳脫的 | 切欄再解析行內：每一列都要剛好四格（五個沒跳脫的 |）。</summary>
    private static void AssertTableRowsHaveFourCells(string markdown)
    {
        foreach (var line in markdown.Split('\n').Where(l => l.StartsWith("| ", StringComparison.Ordinal)))
        {
            var pipes = 0;
            for (var i = 0; i < line.Length; i++)
            {
                if (line[i] == '\\') { i++; continue; }
                if (line[i] == '|') pipes++;
            }
            Assert.True(pipes == 5, $"a table row has {pipes - 1} cell(s): {line}");
        }
    }

    /// <summary>照 CommonMark 拿掉 code span：開頭的反引號串要配到一樣長的，配不到就只是一般文字。</summary>
    private static string OutsideCodeSpans(string markdown)
    {
        var outside = new StringBuilder();
        foreach (var line in markdown.Split('\n'))
        {
            for (var i = 0; i < line.Length;)
            {
                if (line[i] == '\\' && i + 1 < line.Length)
                {
                    outside.Append(line, i, 2);   // code span 外的反斜線才是跳脫
                    i += 2;
                }
                else if (line[i] != '`')
                {
                    outside.Append(line[i++]);
                }
                else
                {
                    var length = RunAt(line, i);
                    var close = FindRun(line, i + length, length);
                    if (close < 0)
                    {
                        outside.Append(line, i, length);
                        i += length;
                    }
                    else
                    {
                        i = close + length;
                    }
                }
            }
            outside.Append('\n');
        }
        return outside.ToString();
    }

    private static int RunAt(string line, int start)
    {
        var end = start;
        while (end < line.Length && line[end] == '`') end++;
        return end - start;
    }

    private static int FindRun(string line, int from, int length)
    {
        for (var i = from; i < line.Length;)
        {
            if (line[i] != '`') { i++; continue; }
            var run = RunAt(line, i);
            if (run == length) return i;
            i += run;
        }
        return -1;
    }

    // ── CLI ────────────────────────────────────────────────────────────────

    [Fact]
    public void The_cli_writes_the_markdown_where_asked_and_its_verdict_matches_the_exit_code()
    {
        var md = Path.Combine(_dir.FullName, "out", "report.md");

        var (exit, _, _) = RunCli("--min-coverage", "0", "--md", md, TestPaths.Demo);
        Assert.Equal(1, exit);
        Assert.True(File.Exists(md));
        var text = File.ReadAllText(md);
        Assert.StartsWith("## XamlKeys - resource key audit", text);
        Assert.Contains(":x: **FAIL**", text);

        // 預設下限：exit 3，報告也要說不可信，而且 stderr 照舊講原因
        var (exit3, _, err) = RunCli("--md", md, TestPaths.Demo);
        Assert.Equal(3, exit3);
        Assert.Contains(":warning: **NOT TRUSTWORTHY**", File.ReadAllText(md));
        Assert.Contains("result is not trustworthy", err);
    }

    [Fact]
    public void Md_without_a_path_is_a_usage_error()
    {
        var (exit, _, err) = RunCli("--md", "--json", "x.json", TestPaths.Demo);
        Assert.Equal(2, exit);
        Assert.Contains("--md takes a path", err);
    }

    private static (int Exit, string Out, string Err) RunCli(params string[] args)
    {
        var psi = new ProcessStartInfo("dotnet")
        {
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            StandardOutputEncoding = Encoding.UTF8,
            StandardErrorEncoding = Encoding.UTF8,
        };
        psi.ArgumentList.Add(TestPaths.CliDll);
        foreach (var a in args) psi.ArgumentList.Add(a);

        using var p = Process.Start(psi)!;
        var o = p.StandardOutput.ReadToEnd();
        var e = p.StandardError.ReadToEnd();
        p.WaitForExit();
        return (p.ExitCode, o, e);
    }
