    [Fact]
    public void A_composed_lookup_in_csharp_cannot_write_markdown()
    {
        // 動態查找的運算式原樣列出（C# 是被掃的 repo 寫的）
        Put("App.xaml", $"<Application {Ns}><Application.Resources><ResourceDictionary><SolidColorBrush x:Key=\"A\" Color=\"#1\" /></ResourceDictionary></Application.Resources></Application>");
        Put("Code.cs", "class C { object F(System.Windows.FrameworkElement e, string n) => e.FindResource(\"[x](http://evil.example) @someone \" + n); }");

